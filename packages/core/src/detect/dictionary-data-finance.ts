// dictionary-packs-compiled.ts for surface collisions before authoring;
// several brief-listed terms (cap table, burn rate, runway, ARR, MRR,
// churn) already exist elsewhere in the built-in dictionary and are
// intentionally NOT re-added here.
//
// gloss_zh uses the standard PRC financial/insurance term where one
// exists (免赔额, 共付额, 归属, 稀释...) with a short clarifier added only
// where the bare term wouldn't land on its own. commonWord: true on
// headwords that are ALSO ordinary English words with an unrelated
// everyday sense (premium, principal, collateral, dilution, withholding,
// itemize) — same suppression semantics as dictionary-data.ts's
// DictTermEntry.commonWord (see modern-usage's own header for the
// mechanism, and scanDictionary's commonWord guard for exact rules).
// "401(k)" is kept as a variant of headword "401k" rather than the other
// way round — "401(k)" ends in a trailing ")" so scanDictionary's
// \b...\b term-boundary regex can never match it as a standalone
// headword in running text (word-boundary \b requires a \w on one side;
// ")" isn't one), it only still matches as a prefix of a glued plural
// like "401(k)s". "401k" has no such issue and is what actually matches
// realistic transcript text.

