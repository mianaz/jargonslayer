// gap, not a technical-vocabulary one: existing packs already cover
// formal meeting-transition phrases (chitchat), softened disagreement
// (softening), and business/project jargon, so this pack instead leans
// into sports metaphors, casual reactions, and classic general-English
// idioms that happen to show up constantly in and around meetings. Off
// by default like every other v0.6 pack — see packs.ts/dictionary.ts for
// wiring. Cross-checked against dictionary-data.ts, dictionary.ts's base
// tables, and dictionary-packs-compiled.ts for surface collisions before
// authoring; several brief-listed phrases (touch base, ballpark,
// playing devil's advocate, I hear you, long story short, the elephant
// in the room, drop the ball, in the weeds, step up to the plate) already
